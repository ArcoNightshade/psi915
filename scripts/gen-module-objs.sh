# Generate the per-module source lists of the DRM/i915 kernel modules
# (build/<module>/Objects.mk) from the import records:
#
#   third_party/IMPORT_FILES   destination, set and licence of every imported
#                              file; this is third_party/manifest/*.list
#                              resolved against the pinned Linux tag by
#                              scripts/import-linux.sh, so it needs no Linux
#                              clone. Files of sets "core" and "link" are
#                              compiled; "inc" files (.c sources that another
#                              file #includes) never are; "extra" files only where a module
#                              asks for them (DRM scheduler, WITH_DRM_SCHED).
#   drm_bsd/MANIFEST           BSD replacements: set "core" .c files
#   third_party/gpl-policy.conf  G1/G2 allow-lists for gpl/
#   drmglue/src/*.c            DRM character device / file layer glue
#
# Module assignment (docs/11-integration-notes.md section 1):
#   linuxkpi_drm     drm/ core+link .c except dma-resv.c; drm_bsd/ outside
#                    drivers/gpu/drm/i915; optionally drm/ scheduler (extra)
#   linuxkpi_gpl_g1  gpl/ files listed "g1" + drm/drivers/dma-buf/dma-resv.c
#                    (MIT; dma-buf.c calls dma_resv_*, docs/08 5.2)
#   linuxkpi_gpl_g2  gpl/ files listed "g2"
#   i915             i915/ core+link .c + drm_bsd/drivers/gpu/drm/i915
#   drmglue sources are listed once (DRMGLUE_SRCS, in build/drm/Objects.mk);
#   the module that links them is chosen in build/drm/Makefile.lkpi
#   (DRMGLUE_IN).
#
# The patches in third_party/patches are already applied to drm/, i915/
# and gpl/ by scripts/import-linux.sh, so the lists name the tree files.
#
# Usage: scripts/gen-module-objs.sh [-c] [-o outdir]
#   -c   check only: exit 1 if a committed Objects.mk is out of date
#   -o   write to outdir/<module>/Objects.mk instead of build/ (testing)
# Portable to illumos /bin/sh (ksh93) and dash; needs awk, sort.
#
set -eu

top=$(cd "$(dirname "$0")/.." && pwd)
out=$top/build
check=0
while getopts "co:h" o; do
	case $o in
	c) check=1 ;;
	o) out=$OPTARG ;;
	*) sed -n '2,/^set -eu/p' "$0" | sed '$d; s/^# \{0,1\}//'; exit 2 ;;
	esac
done

imp=$top/third_party/IMPORT_FILES
pol=$top/third_party/gpl-policy.conf
bsd=$top/drm_bsd/MANIFEST
for f in "$imp" "$pol" "$bsd"; do
	[ -r "$f" ] || { echo "gen-module-objs: missing $f" >&2; exit 1; }
done

tmp=$(mktemp -d "${TMPDIR:-/tmp}/psi915-objs.XXXXXX")
trap 'rm -rf "$tmp"' EXIT INT TERM

pin=$(sed -n 's/^# Generated by .*Upstream //p' "$imp" | head -1)

# imported: set<TAB>path for compiled .c files
awk -F'\t' '!/^#/ && $2 ~ /\.c$/ {print $3 "\t" $2}' "$imp" | sort -k2 >"$tmp/imp"
awk '$1 == "g1" {print "gpl/" $2}' "$pol" | sort >"$tmp/g1"
awk '$1 == "g2" {print "gpl/" $2}' "$pol" | sort >"$tmp/g2"
awk -F'\t' '!/^#/ && $1 == "core" && $2 ~ /\.c$/ {print "drm_bsd/" $2}' "$bsd" | sort >"$tmp/bsd"

sel() {	# $1: awk condition on set ($1) and path ($2)
	awk -F'\t' "$1 {print \$2}" "$tmp/imp"
}

# emit VAR file: a make variable with one source per line
emit() {
	printf '%s =' "$1"
	if [ -s "$2" ]; then
		printf ' \\\n'
		sed 's/^/\t/; $!s/$/ \\/' "$2"
	else
		printf '\n'
	fi
	printf '\n'
}

header() {
	echo "#"
	echo "# Generated by scripts/gen-module-objs.sh; do not edit."
	echo "# Inputs: third_party/IMPORT_FILES (upstream $pin), drm_bsd/MANIFEST,"
	echo "#   third_party/gpl-policy.conf, drmglue/src. Sets compiled: core, link."
	echo "# $1"
	echo "#"
	echo
}

DMARESV=drm/drivers/dma-buf/dma-resv.c

# linuxkpi_drm
sel '($1 == "core" || $1 == "link") && $2 ~ /^drm\// && $2 != "'$DMARESV'" && $2 !~ /\/scheduler\//' \
	| grep -v '^drm/drivers/video/' >"$tmp/drm_core" || true
sel '($1 == "core" || $1 == "link") && $2 ~ /^drm\/drivers\/video\//' >"$tmp/drm_video"
sel '$2 ~ /^drm\/drivers\/gpu\/drm\/scheduler\/.*\.c$/' >"$tmp/drm_sched"
grep -v '^drm_bsd/drivers/gpu/drm/i915/' "$tmp/bsd" >"$tmp/drm_bsd" || true
(cd "$top" && ls drmglue/src/*.c) | sort >"$tmp/drmglue"
sel '$1 == "link" && $2 ~ /^drm\//' >"$tmp/drm_linkset"
mkdir -p "$tmp/out/drm" "$tmp/out/linuxkpi_gpl_g1" "$tmp/out/linuxkpi_gpl_g2" "$tmp/out/i915"
{
	header "linuxkpi_drm: DRM core, KMS/display helpers, TTM, buddy, video, drm_bsd, drmglue."
	emit DRM_SRCS "$tmp/drm_core"
	emit DRM_VIDEO_SRCS "$tmp/drm_video"
	emit DRM_BSD_SRCS "$tmp/drm_bsd"
	echo "# Set \"extra\": not needed by i915; built only with WITH_DRM_SCHED=1."
	emit DRM_SCHED_SRCS "$tmp/drm_sched"
	echo "# drmglue (BSD): linked into the module named by DRMGLUE_IN (Makefile.lkpi)."
	emit DRMGLUE_SRCS "$tmp/drmglue"
	echo "# Informational: the subset of DRM_SRCS that is set \"link\" (non-Gen9 code"
	echo "# compiled for link closure; stub candidates)."
	emit DRM_LINKSET_SRCS "$tmp/drm_linkset"
} >"$tmp/out/drm/Objects.mk"

# linuxkpi_gpl_g1 / g2: only files that are both imported (core/link) and allowed
sel '($1 == "core" || $1 == "link") && $2 ~ /^gpl\//' | sort >"$tmp/gpl_c"
comm -12 "$tmp/gpl_c" "$tmp/g1" >"$tmp/g1_srcs"
comm -12 "$tmp/gpl_c" "$tmp/g2" >"$tmp/g2_srcs"
comm -23 "$tmp/gpl_c" "$tmp/g1" | comm -23 - "$tmp/g2" >"$tmp/gpl_bad"
if [ -s "$tmp/gpl_bad" ]; then
	echo "gen-module-objs: compiled gpl/ files outside the G1/G2 policy:" >&2
	cat "$tmp/gpl_bad" >&2
	exit 1
fi
echo "$DMARESV" >"$tmp/g1_mit"
{
	header "linuxkpi_gpl_g1 (GPL-2.0): dma-buf, dma-fence*, sync_file; plus MIT dma-resv."
	emit GPL_G1_SRCS "$tmp/g1_srcs"
	echo "# MIT, linked into G1 because dma-buf.c calls dma_resv_* (docs/08 5.2)."
	emit GPL_G1_MIT_SRCS "$tmp/g1_mit"
} >"$tmp/out/linuxkpi_gpl_g1/Objects.mk"
{
	header "linuxkpi_gpl_g2 (GPL-2.0): drm_hdcp_helper, drm_gem_framebuffer_helper."
	emit GPL_G2_SRCS "$tmp/g2_srcs"
} >"$tmp/out/linuxkpi_gpl_g2/Objects.mk"

# i915
sel '($1 == "core") && $2 ~ /^i915\//' >"$tmp/i915_core"
sel '($1 == "link") && $2 ~ /^i915\//' >"$tmp/i915_link"
grep '^drm_bsd/drivers/gpu/drm/i915/' "$tmp/bsd" >"$tmp/i915_bsd" || true
{
	header "i915: the Gen9 build set (core) plus link-closure files (link) and drm_bsd."
	emit I915_SRCS "$tmp/i915_core"
	echo "# Set \"link\": non-Gen9 code compiled only so the module links (stub candidates)."
	emit I915_LINK_SRCS "$tmp/i915_link"
	emit I915_BSD_SRCS "$tmp/i915_bsd"
} >"$tmp/out/i915/Objects.mk"

rc=0
for m in drm linuxkpi_gpl_g1 linuxkpi_gpl_g2 i915; do
	dst=$out/$m/Objects.mk
	if [ $check = 1 ]; then
		cmp -s "$tmp/out/$m/Objects.mk" "$dst" || {
			echo "gen-module-objs: $dst is out of date" >&2; rc=1; }
	else
		mkdir -p "$out/$m"
		if ! cmp -s "$tmp/out/$m/Objects.mk" "$dst" 2>/dev/null; then
			cp "$tmp/out/$m/Objects.mk" "$dst.new" && mv -f "$dst.new" "$dst"
			echo "gen-module-objs: wrote $dst" >&2
		fi
	fi
done
[ $check = 1 ] && [ $rc = 0 ] && echo "gen-module-objs: Objects.mk up to date" >&2
exit $rc
