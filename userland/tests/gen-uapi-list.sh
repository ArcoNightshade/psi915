# gen-uapi-list.sh: generate uapi_list.h (ioctl and constant tables) for
# uapi_dump.c from one or more uAPI headers.
#
# usage: gen-uapi-list.sh header.h [header.h ...] > uapi_list.h
#
# Every entry is #ifdef-guarded, so the same generated list compiles against
# any header set (kernel-side or userland-side, older or newer); entries the
# header set lacks are reported as absent. Only names, ioctl argument types and
# number expressions are extracted; no header content is copied.
#
# Portable: POSIX sh + awk (nawk/gawk/mawk; illumos /usr/bin/awk is fine).

set -e
[ $# -ge 1 ] || { echo "usage: $0 header.h ..." >&2; exit 2; }

for h in "$@"; do
	[ -r "$h" ] || { echo "$0: cannot read $h" >&2; exit 2; }
done

echo "/* Generated by userland/tests/gen-uapi-list.sh; do not edit. */"
echo "/* Sources:"
for h in "$@"; do echo " *   $(basename "$h")"; done
echo " */"

cat "$@" | awk '
function trim(s) { sub(/^[ \t]+/, "", s); sub(/[ \t]+$/, "", s); return s }
# Ioctl definitions: #define NAME MACRO(args)
/^#[ \t]*define[ \t]+[A-Z][A-Z0-9_]*[ \t]+(DRM_IO|DRM_IOR|DRM_IOW|DRM_IOWR|_IO|_IOR|_IOW|_IOWR)[ \t]*\(/ {
	line = $0
	sub(/^#[ \t]*define[ \t]+/, "", line)
	name = line; sub(/[ \t].*/, "", name)
	rest = line; sub(/^[A-Z0-9_]+[ \t]+/, "", rest)
	mac = rest; sub(/[ \t]*\(.*/, "", mac)
	args = rest; sub(/^[^(]*\(/, "", args)
	# strip trailing comment and the closing parenthesis
	sub(/\/\*.*$/, "", args); sub(/\/\/.*$/, "", args)
	args = trim(args); sub(/\)[ \t]*$/, "", args)
	if (name in seen) next
	seen[name] = 1
	n = split(args, a, ",")
	if (mac ~ /^DRM_IO/) {
		typ = "DRM_IOCTL_BASE"; nr = trim(a[1]); st = (n >= 2) ? trim(a[2]) : ""
		d = substr(mac, 5)          # IO, IOR, IOW, IOWR
	} else {
		typ = trim(a[1]); nr = trim(a[2]); st = (n >= 3) ? trim(a[3]) : ""
		d = substr(mac, 2)
	}
	if (d == "IO")   dir = "D_NONE"
	if (d == "IOR")  dir = "D_R"
	if (d == "IOW")  dir = "D_W"
	if (d == "IOWR") dir = "D_WR"
	sz = (st == "") ? "0" : "sizeof(" st ")"
	ioc[++ni] = sprintf("#ifdef %s\nE(%s, %s, %s, (%s), %s, \"%s\")\n#else\nA(%s)\n#endif", \
	    name, name, dir, typ, nr, sz, st, name)
	next
}
# ABI constants userland passes to or reads from the kernel.
/^#[ \t]*define[ \t]+(DRM_CAP_|DRM_CLIENT_CAP_|DRM_PRIME_CAP_|DRM_SYNCOBJ_|DRM_EVENT_|DRM_MODE_PAGE_FLIP_|DRM_MODE_ATOMIC_|DRM_MODE_OBJECT_|DRM_MODE_PROP_|DRM_CRTC_SEQUENCE_|DRM_VBLANK_|DRM_CLOEXEC|DRM_RDWR|DRM_COMMAND_BASE|DRM_COMMAND_END|I915_PARAM_|I915_EXEC_|I915_CONTEXT_PARAM_|I915_CONTEXT_CREATE_|I915_CONTEXT_ENGINES_|DRM_I915_QUERY_|I915_MMAP_OFFSET_|I915_MMAP_WC|I915_TILING_|I915_BIT_6_SWIZZLE_|I915_CACHING_|I915_GEM_DOMAIN_|I915_MADV_|I915_USERPTR_|I915_ENGINE_CLASS_|I915_GEM_CREATE_EXT_|I915_OBJECT_PARAM|I915_SCHEDULER_CAP_|I915_GEM_CONTEXT_|I915_GEM_PPGTT_|I915_REG_READ_|I915_RESET_|DMA_BUF_SYNC_|DRM_FORMAT_MOD_VENDOR_INTEL)[A-Z0-9_]*[ \t]/ {
	line = $0
	sub(/^#[ \t]*define[ \t]+/, "", line)
	name = line; sub(/[ \t].*/, "", name)
	val = line; sub(/^[A-Z0-9_]+[ \t]+/, "", val)
	sub(/\/\*.*$/, "", val); val = trim(val)
	if (val == "") next                        # include guards etc.
	if (name ~ /\($/ || line ~ /^[A-Z0-9_]+\(/) next   # function-like
	if (val ~ /"/) next                        # strings
	if (val ~ /^(DRM_IO|_IO)/) next            # ioctls handled above
	if (name in cseen) next
	cseen[name] = 1
	con[++nc] = sprintf("#ifdef %s\nC(%s)\n#else\nCA(%s)\n#endif", name, name, name)
	next
}
END {
	print "\n#ifdef UAPI_WANT_IOCTLS"
	for (i = 1; i <= ni; i++) print ioc[i]
	print "#endif /* UAPI_WANT_IOCTLS */"
	print "\n#ifdef UAPI_WANT_CONSTS"
	for (i = 1; i <= nc; i++) print con[i]
	print "#endif /* UAPI_WANT_CONSTS */"
}'
